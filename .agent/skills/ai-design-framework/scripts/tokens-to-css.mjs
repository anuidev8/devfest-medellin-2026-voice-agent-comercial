#!/usr/bin/env node
// Convert W3C DTCG design tokens into CSS variables.
// Usage: node tokens-to-css.mjs design/design-tokens.json app/design-tokens.css [--plain]
//
// Default output is Tailwind v4: an `@theme` block (so bg-accent, text-muted, rounded-card,
// font-display, ease-calm… work) plus `.dark` overrides. With --plain it writes `:root` only.
//
// Groups: color (+ color.dark overrides), font, fontSize, fontWeight, lineHeight, space, radius,
// shadow, duration, easing. Values may reference other tokens: "{color.accent}".

import fs from "node:fs/promises";
import path from "node:path";

// Tailwind v4 theme namespaces. Groups not listed here go to :root as --<group>-<name>.
const NAMESPACE = {
  color: "color",
  font: "font",
  fontSize: "text",
  fontWeight: "font-weight",
  lineHeight: "leading",
  space: "spacing",
  radius: "radius",
  shadow: "shadow",
  easing: "ease",
};

const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase()).replace(/\./g, "-");

function varName(dotted) {
  const [group, ...rest] = dotted.split(".");
  return `--${NAMESPACE[group] ?? kebab(group)}-${kebab(rest.join("."))}`;
}

// DTCG: a group's $type applies to every token inside it unless the token sets its own.
function flatten(obj, prefix = [], out = {}, inheritedType) {
  const type = obj.$type ?? inheritedType;
  for (const [k, v] of Object.entries(obj)) {
    if (k.startsWith("$")) continue;
    if (v && typeof v === "object" && "$value" in v) out[[...prefix, k].join(".")] = { $type: type, ...v };
    else if (v && typeof v === "object") flatten(v, [...prefix, k], out, type);
  }
  return out;
}

function value(t) {
  const v = t.$value;
  let s;
  if (Array.isArray(v) && t.$type === "cubicBezier") s = `cubic-bezier(${v.join(", ")})`;
  else if (Array.isArray(v)) s = v.map((f) => (/\s/.test(f) && !/^["']/.test(f) ? `"${f}"` : f)).join(", ");
  else if (v && typeof v === "object" && t.$type === "shadow")
    s = `${v.offsetX ?? 0} ${v.offsetY ?? 0} ${v.blur ?? 0} ${v.spread ?? 0} ${v.color}`;
  else s = String(v);
  return s.replace(/\{([^}]+)\}/g, (_, ref) => `var(${varName(ref)})`);
}

const decl = (indent) => ([name, t]) =>
  `${indent}${varName(name)}: ${value(t)};${t.$description ? ` /* ${t.$description} */` : ""}`;

async function main() {
  const args = process.argv.slice(2);
  const plain = args.includes("--plain");
  const [input, output] = args.filter((a) => !a.startsWith("--"));
  if (!input || !output) {
    console.log("Usage: node tokens-to-css.mjs <design-tokens.json> <out.css> [--plain]");
    process.exit(1);
  }
  const tokens = JSON.parse(await fs.readFile(input, "utf8"));
  const darkTokens = tokens.color?.dark;
  if (darkTokens) delete tokens.color.dark;

  const all = Object.entries(flatten(tokens));
  const themed = plain ? [] : all.filter(([n]) => NAMESPACE[n.split(".")[0]]);
  const rootOnly = plain ? all : all.filter(([n]) => !NAMESPACE[n.split(".")[0]]);
  const dark = darkTokens ? Object.entries(flatten(darkTokens)).map(([n, t]) => [`color.${n}`, t]) : [];
  const durations = all.filter(([n]) => n.startsWith("duration."));

  const out = ["/* Generated by ai-design-framework/scripts/tokens-to-css.mjs — edit design/design-tokens.json, then re-run. */"];
  if (themed.length) out.push("", "@theme {", ...themed.map(decl("  ")), "}");
  if (rootOnly.length) out.push("", ":root {", ...rootOnly.map(decl("  ")), "}");
  if (dark.length) {
    out.push("", ".dark {", ...dark.map(decl("  ")), "}");
    out.push("", "@media (prefers-color-scheme: dark) {", "  :root:not(.light) {", ...dark.map(decl("    ")), "  }", "}");
  }
  if (durations.length) {
    out.push("", "/* Reduced motion: durations collapse; components must also swap movement for opacity. */");
    out.push("@media (prefers-reduced-motion: reduce) {", "  :root {", ...durations.map(([n]) => `    ${varName(n)}: 1ms;`), "  }", "}");
  }
  out.push("");

  await fs.mkdir(path.dirname(path.resolve(output)), { recursive: true });
  await fs.writeFile(output, out.join("\n"));
  console.log(`${all.length} tokens (+${dark.length} dark) → ${path.resolve(output)}`);
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
